/**
 * Regenerate (or with --check, verify) the release-script manifest that the
 * boot-time schema check compares against. The manifest is committed because
 * hosts bundle core, so the check cannot read the SQL files at runtime.
 */
import { readFileSync, writeFileSync } from 'node:fs'

import { readReleaseScripts } from '../src/database/schema-scripts/files.js'

const MANIFEST = new URL('../src/database/schema-scripts/manifest.gen.ts', import.meta.url)

const render = (): string => {
  const entries = readReleaseScripts()
    .map(({ name, checksum }) => `  { name: '${name}', checksum: '${checksum}' },`)
    .join('\n')
  return `// Generated by \`pnpm schema:manifest\`. Do not edit.
import type { ScriptRecord } from './compare.js'

export const RELEASE_SCRIPTS: readonly ScriptRecord[] = [
${entries}
]
`
}

const expected = render()
if (process.argv.includes('--check')) {
  if (readFileSync(MANIFEST, 'utf8') !== expected) {
    console.error('release-script manifest is stale; run `pnpm schema:manifest`')
    process.exit(1)
  }
} else {
  writeFileSync(MANIFEST, expected)
}
