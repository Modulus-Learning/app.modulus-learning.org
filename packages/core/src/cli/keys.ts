import { generateKeyPairSync, randomBytes } from 'node:crypto'

/**
 * Print a fresh set of installation keys as environment variables, in the
 * encodings the configuration loaders expect: RS256 key pairs as base64 of
 * PEM, and a base64 32-byte session secret. Nothing is written to disk.
 */

const rsaPair = () => {
  const { privateKey, publicKey } = generateKeyPairSync('rsa', {
    modulusLength: 2048,
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    publicKeyEncoding: { type: 'spki', format: 'pem' },
  })
  const base64 = (pem: string) => Buffer.from(pem).toString('base64')
  return { privateKey: base64(privateKey), publicKey: base64(publicKey) }
}

export const runKeys = (command: string | undefined): number => {
  if (command !== 'generate') return 2
  const api = rsaPair()
  const lti = rsaPair()
  const keyId = `modulus-${new Date().toISOString().slice(0, 10)}-${randomBytes(4).toString('hex')}`
  console.log(`# Generated by \`modulus keys generate\`. Keep these secret.

# Signs and verifies Modulus access tokens.
API_JWT_PRIVATE_KEY=${api.privateKey}
API_JWT_PUBLIC_KEY=${api.publicKey}

# Signs LTI messages and client assertions; the public key is served at the JWKS endpoint.
LTI_JWKS_KEY_ID=${keyId}
LTI_JWKS_PRIVATE_KEY=${lti.privateKey}
LTI_JWKS_PUBLIC_KEY=${lti.publicKey}

# Encrypts the host's session cookies.
SESSION_SECRET=${randomBytes(32).toString('base64')}`)
  return 0
}
